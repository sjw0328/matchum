@pytest.mark.parametrize("src,expected", CASES)
def test_corrects(src, expected):
    assert check(src).checked == expected


@pytest.mark.parametrize("src", CLEAN)
def test_no_false_positive(src):
    r = check(src)
    assert not r.corrections, r.corrections


def test_warning_reported_not_applied():
    r = check("그게 제 바램이에요")
    assert r.checked == "그게 제 바램이에요"
    assert r.corrections and r.corrections[0].level is Level.WARNING
    assert check("그게 제 바램이에요", apply_warnings=True).checked == "그게 제 바람이에요"


def test_loanword_is_warning():
    r = check("메세지를 보냈다")
    assert r.checked == "메세지를 보냈다"
    assert check("메세지를 보냈다", apply_warnings=True).checked == "메시지를 보냈다"


def test_ignore_and_custom_rule():
    c = Checker(ignore=["됬"]).add_rule(WordRule("my.001", "어케", "어떻게"))
    assert c.check("어케 됬어").checked == "어떻게 됬어"


def test_positions_point_at_original():
    text = "몇일 뒤 연락할께요. 할수있다"
    for c in check(text).corrections:
        assert text[c.start:c.end] == c.original


def test_rule_ids_unique():
    ids = [r.id for r in DEFAULT_RULES]
    assert len(ids) == len(set(ids))


def test_hanspell_compat():
    r = spell_checker.check("몇일 뒤에 봐요")
    assert r.checked == "며칠 뒤에 봐요"
    assert r.errors == 1
    assert set(r.as_dict()) >= {"result", "original", "checked", "errors", "words", "time"}
