class Level(str, Enum):
    ERROR = "error"      # 문맥과 무관하게 틀린 표기 — 기본적으로 자동 교정
    WARNING = "warning"  # 문맥에 따라 맞을 수도 있는 표기 — 기본적으로 보고만 함


class Category(str, Enum):
    SPELLING = "spelling"  # 맞춤법
    SPACING = "spacing"    # 띄어쓰기
    STYLE = "style"        # 표준어·문체 권고


@dataclass(frozen=True)
class Correction:
    start: int          # 원문 기준 시작 인덱스
    end: int            # 원문 기준 끝 인덱스 (exclusive)
    original: str
    suggestion: str
    rule_id: str
    message: str
    level: Level = Level.ERROR
    category: Category = Category.SPELLING


@dataclass
class Result:
    original: str
    checked: str
    corrections: List[Correction] = field(default_factory=list)
    time: float = 0.0

    @property
    def errors(self) -> int:
        return len(self.corrections)

    @property
    def ok(self) -> bool:
        return not self.corrections

    def as_dict(self) -> Dict:
        return {
            "original": self.original,
            "checked": self.checked,
            "errors": self.errors,
            "time": self.time,
            "corrections": [
                {
                    "start": c.start,
                    "end": c.end,
                    "original": c.original,
                    "suggestion": c.suggestion,
                    "rule": c.rule_id,
                    "message": c.message,
                    "level": c.level.value,
                    "category": c.category.value,
                }
                for c in self.corrections
            ],
        }


